// jtxexex_main and the real jtxexex_video, wired as jtxexex_game wires them, so the
// boot's tests of palette, tile and sprite RAM run against the video modules' own RAMs,
// and IRQ5 comes from the object chip's DMA. The program ROM, the EEPROM and the
// K054321 are the testbench's (tb.cpp); the graphics ROM buses read 0.
module mainvid(
    input             rst,
    input             clk,
    input             pxl_cen,
    input             pxl2_cen,
    // program ROM
    output     [20:1] main_addr,
    output            rom_cs,
    input      [15:0] rom_data,
    input             rom_ok,
    output     [ 1:0] ram_dsn,
    output     [15:0] cpu_dout,
    output            cpu_we,
    // work RAM, block RAM in the testbench
    output            ram_cs,
    input      [15:0] ram_dout,
    output     [ 1:0] ram_we,
    // EEPROM
    output     [ 6:0] nv_addr,
    input      [ 7:0] nv_dout,
    output     [ 7:0] nv_din,
    output            nv_we,
    // sound side, replayed
    input      [ 7:0] pair_dout,
    output            pair_we,
    output            sndon,
    output            LVBL
);

wire        scrreg_cs, tilesys_cs, scr_cs, objreg_cs, objsys_cs, objcha_n, col_cs, pcu_cs,
